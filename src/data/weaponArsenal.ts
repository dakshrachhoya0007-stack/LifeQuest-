    speed: bp.speed,
    element: bp.element,
    abilityPower: bp.abilityPower,
    specialAbilityName: bp.specialAbilityName,
    specialAbilitySummary: bp.specialAbilitySummary,
    combatIntegrationStatus: bp.combatIntegrationStatus,
    obtainMethod: bp.obtainMethod,
    unlockRequirement: bp.unlockRequirement,
    evolutionPath: bp.evolutionPath,
    awakened: bp.awakened,
    awakeningLevel: bp.awakeningLevel,
    upgradeForgeCost: bp.upgradeForgeCost,
    unlocked: false,
    equipped: false,
    description: bp.description,
    lore: bp.lore,
