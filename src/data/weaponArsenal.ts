export const getMasteryPathForCategory = (category: WeaponCategory): MasteryPath => {
  switch (category) {
    case 'Bows':
    case 'Crossbows':
    case 'Dual Blades':
    case 'Spears':
      return 'Endurance';
    case 'Magic Staffs':
    case 'Wands':
    case 'Daggers':
    case 'Scythes':
    case 'Helmets':
    case 'Accessories':
      return 'Focus';
    case 'Shields':
    case 'Armour':
      return 'Recovery';
    default:
      return 'Strength';
  }
};

